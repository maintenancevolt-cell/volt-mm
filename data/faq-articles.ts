export function getFAQArticleBySlug(slug: string): FAQArticle | undefined {
  return faqArticles.find(
    (a) => a.slug === slug || a.slug === decodeURIComponent(slug),
  );
}

export function getFAQArticlesByServiceId(serviceId: string): FAQArticle[] {
  return faqArticles.filter((a) => a.serviceId === serviceId);
}
